// Writes lib/features/vaccines/vaccine_schedule.g.dart from packages/contracts (vaccines.ts), the
// single source of the Sổ tiêm chủng reference schedule (P-133). Build contracts first:
//   pnpm --filter @child-life/contracts run build && node tool/vaccine_schedule.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { vaccineSchedule, vaccineScheduleVersion } from '../../../packages/contracts/dist/index.js';

const q = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const text = (t) => `(vi: ${q(t.vi)}, en: ${q(t.en)})`;
const rows = vaccineSchedule.map(
  (v) => `  VaccineDef(
    id: ${q(v.id)},
    name: ${text(v.name)},
    short: ${text(v.short)},
    months: [${v.months.join(', ')}],
    programme: VaccineProgramme.${v.programme},
    route: VaccineRoute.${v.route},
    about: ${text(v.about)},
    minIntervalWeeks: ${v.minIntervalWeeks ?? 'null'},
    yearly: ${v.yearly === true},
    only5in1: ${v.only5in1 === true},
    dtpSeries: ${v.dtpSeries === true},
  ),`,
);
const out = `// GENERATED by tool/vaccine_schedule.mjs from packages/contracts/src/vaccines.ts. Do not edit.
import 'vaccine_models.dart';

const vaccineScheduleVersion = ${vaccineScheduleVersion};

const vaccineSchedule = <VaccineDef>[
${rows.join('\n')}
];
`;
const target = fileURLToPath(new URL('../lib/features/vaccines/vaccine_schedule.g.dart', import.meta.url));
writeFileSync(target, out);
console.log(`${vaccineSchedule.length} vaccines -> lib/features/vaccines/vaccine_schedule.g.dart`);
