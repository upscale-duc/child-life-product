// Writes lib/features/vaccines/vaccine_schedule.g.dart from packages/contracts (vaccines.ts), the
// single source of the Sổ tiêm chủng reference schedule (P-133). Build contracts first:
//   pnpm --filter @child-life/contracts run build && node tool/vaccine_schedule.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import {
  countryVaccineSchedules,
  vaccineSchedule,
  vaccineScheduleVersion,
} from '../../../packages/contracts/dist/index.js';

const q = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const text = (t) => `(vi: ${q(t.vi)}, en: ${q(t.en)})`;
const row = (v, indent = '  ') =>
  `${indent}VaccineDef(
${indent}  id: ${q(v.id)},
${indent}  name: ${text(v.name)},
${indent}  short: ${text(v.short)},
${indent}  months: [${v.months.join(', ')}],
${indent}  programme: VaccineProgramme.${v.programme},
${indent}  route: VaccineRoute.${v.route},
${indent}  about: ${text(v.about)},
${indent}  minIntervalWeeks: ${v.minIntervalWeeks ?? 'null'},
${indent}  yearly: ${v.yearly === true},
${indent}  only5in1: ${v.only5in1 === true},
${indent}  dtpSeries: ${v.dtpSeries === true},
${indent}),`;
const rows = vaccineSchedule.map((v) => row(v));
const countries = Object.values(countryVaccineSchedules).map(
  (c) => `  ${q(c.country)}: CountryVaccineSchedule(
    country: ${q(c.country)},
    programmeName: ${text(c.programmeName)},
    checkedOn: ${q(c.checkedOn)},
    sources: [${c.sources.map((x) => `(label: ${q(x.label)}, url: ${q(x.url)})`).join(', ')}],
    defs: [
${c.defs.map((v) => row(v, '      ')).join('\n')}
    ],
  ),`,
);
const out = `// GENERATED by tool/vaccine_schedule.mjs from packages/contracts/src/vaccines.ts. Do not edit.
import 'vaccine_models.dart';

const vaccineScheduleVersion = ${vaccineScheduleVersion};

const vaccineSchedule = <VaccineDef>[
${rows.join('\n')}
];

/// Routine schedules outside Việt Nam (D-084), from contracts/src/vaccine-countries.ts.
const countryVaccineSchedules = <String, CountryVaccineSchedule>{
${countries.join('\n')}
};
`;
const target = fileURLToPath(new URL('../lib/features/vaccines/vaccine_schedule.g.dart', import.meta.url));
writeFileSync(target, out);
console.log(
  `${vaccineSchedule.length} vaccines + ${countries.length} countries -> lib/features/vaccines/vaccine_schedule.g.dart`,
);
