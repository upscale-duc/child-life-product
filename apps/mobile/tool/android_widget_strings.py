#!/usr/bin/env python3
"""The Android widget picker's names and descriptions (android-plan.md A5). Android draws them
before the app ever runs, so they cannot come through the glance snapshot: this writes
android/app/src/main/res/values{,-en}/widget_strings.xml from the ARB catalogs (D-012; Vietnamese
is the default, English the `en` variant), so ARB stays the only place to edit them (as
tool/s8_widget_strings.py does for iOS). Run from apps/mobile:

    python3 tool/android_widget_strings.py
"""

import json
import pathlib
from xml.sax.saxutils import escape

ROOT = pathlib.Path(__file__).resolve().parent.parent
RES = ROOT / "android/app/src/main/res"
KEYS = [
    ("widget_bottle", "glanceGalleryBottle"),
    ("widget_breast", "glanceGalleryBreast"),
    ("widget_sleep", "glanceGallerySleep"),
    ("widget_diaper", "glanceGalleryDiaper"),
    ("widget_quick", "glanceGalleryQuick"),
    ("widget_today", "glanceGalleryToday"),
    ("widget_camera", "glanceGalleryCamera"),
    ("widget_library", "glanceGalleryLibrary"),
]


def write(arb: str, folder: str):
    values = json.loads((ROOT / "lib/l10n" / arb).read_text())
    rows = []
    for res, key in KEYS:
        for suffix, part in (("name", "Name"), ("description", "Blurb")):
            text = escape(values[key + part]).replace("'", "\\'")
            rows.append(f'    <string name="{res}_{suffix}">{text}</string>')
    out = RES / folder / "widget_strings.xml"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"<!-- Generated by tool/android_widget_strings.py from lib/l10n/{arb}. -->\n"
        "<resources>\n" + "\n".join(rows) + "\n</resources>\n"
    )
    print(out.relative_to(ROOT))


write("app_vi.arb", "values")
write("app_en.arb", "values-en")
