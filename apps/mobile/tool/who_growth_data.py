# 20i / 20d: WHO Child Growth Standards weight-for-age, length/height-for-age and (owner decision
# 2026-10-16) head-circumference-for-age, hard-coded into the app (owner request 2026-10-11).
# Source: WHO anthro, data-raw/growthstandards/{weianthro,lenanthro,hcanthro}.txt (https://github.com/WorldHealthOrganization/anthro), LMS parameters by
# day of age (0–1856 days), sex 1 = boy, 2 = girl.
#
# Writes lib/features/care/who_growth_data.g.dart with rows [day, L, M, S]: every day for the first
# 13 weeks, every week to 2 years, every month to 5 years (LMS is smooth; the app interpolates).
#
# Usage: python3 tool/who_growth_data.py <dir with weianthro.txt, lenanthro.txt and hcanthro.txt>
import pathlib, sys

src = pathlib.Path(sys.argv[1])
out = pathlib.Path(__file__).resolve().parent.parent / 'lib' / 'features' / 'care' / 'who_growth_data.g.dart'


def load(name):
    table = {1: {}, 2: {}}
    for line in (src / f'{name}.txt').read_text().splitlines():
        cols = line.strip().split('\t')
        if not cols or cols[0] == 'sex':
            continue
        table[int(cols[0])][int(cols[1])] = (float(cols[2]), float(cols[3]), float(cols[4]))
    return table


days = sorted(set(list(range(0, 92)) + list(range(91, 731, 7)) + [730]
                  + [round(m * 30.4375) for m in range(24, 61)]))
days = [d for d in days if d <= 1856]


def rows(table, sex):
    out = []
    for d in days:
        L, M, S = table[sex][d]
        out.append(f'{d}, {L:g}, {M:g}, {S:g}')
    return ',\n  '.join(out)


wei, length, head = load('weianthro'), load('lenanthro'), load('hcanthro')
parts = [
    '// GENERATED by tool/who_growth_data.py from the WHO Child Growth Standards (WHO anthro,\n'
    '// github.com/WorldHealthOrganization/anthro). Do not edit by hand.\n'
    '//\n'
    '// Rows of [age in days, L, M, S]; values between rows are interpolated.\n'
    '// ignore_for_file: public_member_api_docs\n',
]
for name, table, sex in [
    ('whoWeightBoys', wei, 1), ('whoWeightGirls', wei, 2),
    ('whoLengthBoys', length, 1), ('whoLengthGirls', length, 2),
    ('whoHeadBoys', head, 1), ('whoHeadGirls', head, 2),
]:
    parts.append(f'\nconst {name} = <double>[\n  {rows(table, sex)},\n];\n')
out.write_text(''.join(parts))
print(f'{len(days)} ages per table -> {out.name}')
