#!/usr/bin/env python3
"""The widget art for Android (android-plan.md A5): converts the iOS widget's SVGs
(ios/widget/Assets.xcassets/*.imageset/*.svg) into VectorDrawables under
android/app/src/main/res/drawable/, so both platforms draw the same pictures.

Handles what those files use: <path> with fill / stroke / stroke-width / stroke-linecap /
fill-opacity / opacity, <use> of a path in <defs>, and clip-path on a path (an inner stroke) or
on the whole picture (ignored when it is the full canvas). Run from apps/mobile:

    python3 tool/android_widget_art.py
"""

import pathlib
import re
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "ios/widget/Assets.xcassets"
OUT = ROOT / "android/app/src/main/res/drawable"
SVG = "{http://www.w3.org/2000/svg}"
XLINK = "{http://www.w3.org/1999/xlink}href"
NAMES = {
    "MiniBottle": "widget_art_bottle",
    "MiniDrop": "widget_art_breast",
    "MiniMoon": "widget_art_sleep",
    "MiniDiaper": "widget_art_diaper",
    "BabyFace": "widget_art_baby",
}


def color(value: str, opacity: float) -> str:
    v = value.strip()
    if v.lower() == "white":
        v = "#FFFFFF"
    if v.lower() == "black":
        v = "#000000"
    if not re.fullmatch(r"#[0-9A-Fa-f]{6}", v):
        raise ValueError(f"colour {value!r} not handled")
    alpha = round(max(0.0, min(1.0, opacity)) * 255)
    return f"#{alpha:02X}{v[1:].upper()}"


def path_xml(d: str, attrs: dict, indent: str) -> str:
    opacity = float(attrs.get("opacity", "1"))
    out = [f'{indent}<path', f'{indent}    android:pathData="{d}"']
    fill = attrs.get("fill")
    if fill and fill != "none":
        out.append(f'{indent}    android:fillColor="{color(fill, opacity * float(attrs.get("fill-opacity", "1")))}"')
    stroke = attrs.get("stroke")
    if stroke and stroke != "none":
        out.append(f'{indent}    android:strokeColor="{color(stroke, opacity * float(attrs.get("stroke-opacity", "1")))}"')
        out.append(f'{indent}    android:strokeWidth="{attrs.get("stroke-width", "1")}"')
        cap = attrs.get("stroke-linecap")
        if cap in ("round", "square", "butt"):
            out.append(f'{indent}    android:strokeLineCap="{cap}"')
        join = attrs.get("stroke-linejoin")
        if join in ("round", "miter", "bevel"):
            out.append(f'{indent}    android:strokeLineJoin="{join}"')
    out[-1] += " />"
    return "\n".join(out)


def convert(svg: pathlib.Path) -> str:
    tree = ET.parse(svg)
    root = tree.getroot()
    width, height = root.get("width"), root.get("height")
    vb = root.get("viewBox", f"0 0 {width} {height}").split()
    defs = {}
    clips = {}
    for el in root.iter():
        if el.tag == f"{SVG}path" and el.get("id"):
            defs[el.get("id")] = el.get("d")
    for el in root.iter(f"{SVG}clipPath"):
        child = list(el)[0]
        if child.tag == f"{SVG}use":
            clips[el.get("id")] = defs[child.get(XLINK).lstrip("#")]
        elif child.tag == f"{SVG}rect":
            # A full-canvas rectangle clips nothing.
            clips[el.get("id")] = None
        elif child.tag == f"{SVG}path":
            clips[el.get("id")] = child.get("d")

    body = []

    def walk(el):
        for child in el:
            tag = child.tag
            if tag in (f"{SVG}defs", f"{SVG}clipPath"):
                continue
            if tag == f"{SVG}g":
                walk(child)
            elif tag == f"{SVG}use":
                d = defs[child.get(XLINK).lstrip("#")]
                body.append(path_xml(d, dict(child.attrib), "    "))
            elif tag == f"{SVG}path":
                attrs = dict(child.attrib)
                clip = attrs.get("clip-path")
                clip_d = clips.get(clip[5:-1]) if clip else None
                if clip_d:
                    body.append("    <group>")
                    body.append(f'        <clip-path android:pathData="{clip_d}" />')
                    body.append(path_xml(attrs["d"], attrs, "        "))
                    body.append("    </group>")
                else:
                    body.append(path_xml(attrs["d"], attrs, "    "))

    walk(root)
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"<!-- Generated by tool/android_widget_art.py from ios/widget/Assets.xcassets/{svg.parent.name}. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{width}dp"\n'
        f'    android:height="{height}dp"\n'
        f'    android:viewportWidth="{vb[2]}"\n'
        f'    android:viewportHeight="{vb[3]}">\n'
        + "\n".join(body)
        + "\n</vector>\n"
    )


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for asset, name in NAMES.items():
        svg = next((SRC / f"{asset}.imageset").glob("*.svg"))
        (OUT / f"{name}.xml").write_text(convert(svg))
        print(f"{name}.xml  <-  {svg.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
