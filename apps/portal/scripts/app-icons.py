# Copies the app's line icons, logo mark and palettes into the portal's phone previews (Cập nhật ứng
# dụng, D-061), so the preview draws exactly what the app draws. Re-run after an icon changes:
# python3 apps/portal/scripts/app-icons.py
import pathlib, re, json

root = pathlib.Path(__file__).resolve().parents[3]
icons = root / 'apps/mobile/assets/icons'
names = ['alert', 'grid', 'heart', 'cake', 'spark', 'bell', 'camera', 'sleep', 'family', 'star',
         'lock', 'arrow-right', 'close', 'retry', 'cloud-off']

def inner(svg: str) -> str:
    body = re.sub(r'^.*?<svg[^>]*>', '', svg, flags=re.S)
    body = re.sub(r'</svg>\s*$', '', body, flags=re.S)
    body = re.sub(r'\s(id|xmlns)="[^"]*"', '', body)
    return re.sub(r'\s+', ' ', body).strip()

def attrs(svg: str) -> str:
    m = re.search(r'<svg([^>]*)>', svg)
    keep = re.findall(r'\s(fill|stroke|stroke-width|stroke-linecap|stroke-linejoin)="([^"]*)"', m.group(1))
    return ' '.join(f'{k}="{v}"' for k, v in keep)

out = {n: {'attrs': attrs(s := (icons / f'{n}.svg').read_text()), 'body': inner(s)} for n in names}
mark = (root / 'apps/mobile/assets/logo/mark-color.svg').read_text()
vb = re.search(r'viewBox="([^"]*)"', mark).group(1)
ts = ['// Generated by scripts/app-icons.py from apps/mobile/assets and the design tokens. Do not edit.',
      '',
      f'export const appIcons: Record<string, {{ attrs: string; body: string }}> = {json.dumps(out, ensure_ascii=False, indent=2)};',
      '',
      f'export const appMark = {json.dumps({"viewBox": vb, "body": inner(mark)})};',
      '']
# The app's palettes, so the preview shows Light or Night care whatever the portal's theme.
tokens = (root / 'packages/design-tokens/dist/tokens.css').read_text()
def block(selector: str) -> dict:
    start = tokens.index(selector)
    body = tokens[tokens.index('{', start) + 1:tokens.index('}', start)]
    return {k: v for k, v in re.findall(r'(--[a-z0-9-]+):\s*([^;]+);', body) if v.startswith(('#', 'rgb'))}
palettes = {'light': block(':root {'), 'night': block(':root[data-theme="night-care"]')}
ts += [f'export const appPalettes: Record<"light" | "night", Record<string, string>> = {json.dumps(palettes, indent=2)};', '']
(root / 'apps/portal/src/app-icons.ts').write_text('\n'.join(ts))
print(len(out), 'icons')
