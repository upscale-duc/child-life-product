// Reuse the application's WHO LMS source; no separately maintained reference numbers.
import { readFileSync, writeFileSync } from 'node:fs';
import { format } from 'prettier';
import { URL } from 'node:url';
const source = readFileSync(
  new URL('../../../apps/mobile/lib/features/care/who_growth_data.g.dart', import.meta.url),
  'utf8',
);
const tables = Object.fromEntries(
  [...source.matchAll(/const (who\w+) = <double>\[([\s\S]*?)\];/g)].map(([, name, body]) => [
    name,
    body
      .split(',')
      .map((s) => s.trim())
      .filter(Boolean)
      .map(Number),
  ]),
);
if (
  Object.keys(tables).length !== 6 ||
  Object.values(tables).some((t) => t.length % 4 !== 0 || t.some((n) => !Number.isFinite(n)))
)
  throw Error('Invalid WHO source tables');
writeFileSync(
  new URL('../src/assistant-growth-data.g.ts', import.meta.url),
  await format(
    '// GENERATED by scripts/generate-assistant-growth.mjs from the app WHO LMS tables.\nexport const whoLms: Record<string, number[]> = ' +
      JSON.stringify(tables) +
      ';\n',
    { parser: 'typescript', printWidth: 100, singleQuote: true, trailingComma: 'all' },
  ),
);
