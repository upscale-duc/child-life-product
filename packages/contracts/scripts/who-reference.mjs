// Generates src/who-reference.g.ts: WHO P3 / median / P97 rows (weekly 0–13, monthly 0–60) from the
// LMS tables the app ships (apps/mobile/lib/features/care/who_growth_data.g.dart, D-049). This is
// version 1 of the "growth.*" reference datasets (P-138), so portal-managed tables start out
// giving the same results as the app. Run: node packages/contracts/scripts/who-reference.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '../../..');
const dart = readFileSync(
  join(root, 'apps/mobile/lib/features/care/who_growth_data.g.dart'),
  'utf8',
);
const table = (name) => {
  const m = dart.match(new RegExp(`const ${name} = <double>\\[([^\\]]*)\\]`));
  if (!m) throw new Error(`missing ${name}`);
  const nums = m[1]
    .split(',')
    .map((s) => s.trim())
    .filter(Boolean)
    .map(Number);
  const rows = [];
  for (let i = 0; i < nums.length; i += 4) rows.push(nums.slice(i, i + 4));
  return rows;
};
const Z = 1.880793608; // P3 / P97, as WhoGrowth.zBand
const at = (rows, day) => {
  let lo = rows[0];
  let hi = rows[rows.length - 1];
  for (let i = 0; i < rows.length - 1; i++) {
    if (rows[i][0] <= day && rows[i + 1][0] >= day) {
      lo = rows[i];
      hi = rows[i + 1];
      break;
    }
  }
  const t = hi[0] === lo[0] ? 0 : (day - lo[0]) / (hi[0] - lo[0]);
  const [L, M, S] = [1, 2, 3].map((k) => lo[k] + (hi[k] - lo[k]) * t);
  const x = (z) => (Math.abs(L) < 1e-9 ? M * Math.exp(S * z) : M * (1 + L * S * z) ** (1 / L));
  const r = (v) => Math.round(v * 100) / 100;
  return { low: r(x(-Z)), median: r(M), high: r(x(Z)) };
};
const build = (boys, girls) => {
  const out = [];
  for (const [sex, rows] of [
    ['boy', boys],
    ['girl', girls],
  ]) {
    for (let w = 0; w <= 13; w++) out.push({ sex, unit: 'week', age: w, ...at(rows, w * 7) });
    for (let m = 0; m <= 60; m++)
      out.push({ sex, unit: 'month', age: m, ...at(rows, Math.round(m * 30.4375)) });
  }
  return out;
};
const weight = build(table('whoWeightBoys'), table('whoWeightGirls'));
const length = build(table('whoLengthBoys'), table('whoLengthGirls'));
const fmt = (rows) =>
  rows
    .map(
      (r) =>
        `    { sex: '${r.sex}', unit: '${r.unit}', age: ${r.age}, low: ${r.low}, median: ${r.median}, high: ${r.high} },`,
    )
    .join('\n');
writeFileSync(
  join(root, 'packages/contracts/src/who-reference.g.ts'),
  `// GENERATED by scripts/who-reference.mjs from the WHO LMS tables the app ships. Do not edit.\n` +
    `// P3 / median / P97 (kg for weight, cm for length); version 1 of the growth datasets (P-138).\n` +
    `import type { GrowthRow } from './reference.js';\n\n` +
    `export const whoReferenceRows: { weight: GrowthRow[]; length: GrowthRow[] } = {\n` +
    `  weight: [\n${fmt(weight)}\n  ],\n  length: [\n${fmt(length)}\n  ],\n};\n`,
);
console.log(`weight ${weight.length} rows, length ${length.length} rows`);
